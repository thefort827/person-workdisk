/**
 * 导入数据到知识库
 */
async function importToKnowledge(rows) {
  return new Promise((resolve, reject) => {
    const postData = JSON.stringify({ rows: rows });
    
    const options = {
      hostname: 'localhost',
      port: 3000,
      path: '/api/import?entity=knowledge',
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(postData),
      },
    };
    
    const req = http.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        try {
          const result = JSON.parse(data);
          resolve(result);
        } catch (e) {
          reject(new Error(`解析响应失败: ${data}`));
        }
      });
    });
    
    req.on('error', (e) => {
      reject(e);
    });
    
    req.write(postData);
    req.end();
  });
}

/**
 * 主函数
 */
async function main() {
  console.log('快速导入CPA核心学习资料到财务知识库...');
  
  try {
    const result = await importToKnowledge(CORE_MATERIALS);
    if (result.ok) {
      console.log(`成功导入 ${result.inserted || CORE_MATERIALS.length} 条CPA核心学习资料`);
      console.log('您可以在财务知识库页面查看这些资料');
    } else {
      console.error(`导入失败: ${result.error}`);
    }
  } catch (error) {
    console.error(`导入出错: ${error.message}`);
  }
}

// 运行主函数
main();